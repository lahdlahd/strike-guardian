/**
 * Print a Markdown "Results" section straight from the signed ledger.
 * Every number comes from verified artifacts — nothing typed by hand.
 *   npm run report
 */
import "dotenv/config";
import { openStore } from "../lib/artifacts/store.ts";
import { verifyArtifact, type Artifact } from "../lib/artifacts/artifact.ts";
import type { GuardianDecision, GuardianContext } from "../lib/guardian/engine.ts";
import { isolatedLiqPrice, mmrFor } from "../lib/guardian/market-math.ts";

const store = openStore();
await store.init();
const all: Artifact[] = [];
let before: number | undefined;
for (;;) {
  const page = await store.list({ limit: 500, beforeSeq: before });
  if (!page.length) break;
  all.push(...page);
  before = page.at(-1)!.seq;
}
all.reverse();

let valid = true;
for (let i = 0; i < all.length; i++) {
  const v = verifyArtifact(all[i], i ? all[i - 1] : undefined);
  if (!(v.hashOk && v.signatureOk && (v.chainOk ?? true))) valid = false;
}

const liveBoots = all.filter((a) => a.kind === "boot" && (a.body as { live?: boolean }).live);
const liveSince = liveBoots[0]?.createdAt;
const live = all.filter((a) => liveSince && a.createdAt >= liveSince);
const decisions = live.filter((a) => a.kind === "decision") as Artifact<{ decision: GuardianDecision; inputs?: GuardianContext }>[];
const v = { APPROVE: 0, BLOCK: 0, PAUSE: 0 } as Record<string, number>;
const reasons: Record<string, number> = {};
for (const a of decisions) {
  const d = a.body.decision;
  v[d.verdict] = (v[d.verdict] ?? 0) + 1;
  if (d.verdict !== "APPROVE") for (const c of d.checks) if (!c.passed) reasons[c.name] = (reasons[c.name] ?? 0) + 1;
}
const execs = live.filter((a) => a.kind === "execution");
const outcomes = live.filter((a) => a.kind === "outcome") as Artifact<{ result: string; pnlUsdApprox: number }>[];
const wins = outcomes.filter((o) => o.body.result === "win").length;
const losses = outcomes.filter((o) => o.body.result === "loss").length;
const pnl = outcomes.reduce((s, o) => s + (o.body.pnlUsdApprox ?? 0), 0);
const hb = await store.getState<{ equity: number; positions: { symbol: string; size: string; entry: string; liq: string; leverage: number }[] }>("heartbeat");

// Liquidation: Guardian's isolated-margin formula at Strike's actual entry vs Strike's own figure, for open positions.
const liqRows: string[] = [];
for (const p of hb?.positions ?? []) {
  const lastDecision = [...decisions].reverse().find((a) => a.body.decision.symbol === p.symbol && a.body.decision.verdict === "APPROVE");
  const market = lastDecision?.body.inputs?.market;
  if (!market || !Number(p.liq)) continue;
  const entry = Number(p.entry);
  const side = Number(p.size) > 0 ? "long" : "short";
  const notional = Math.abs(Number(p.size)) * entry;
  const est = isolatedLiqPrice(entry, side, p.leverage || 3, mmrFor(market, notional).mmr);
  const diffPct = (Math.abs(est - Number(p.liq)) / Number(p.liq)) * 100;
  liqRows.push(`| ${p.symbol} ${side} @ ${entry} | ${est.toFixed(0)} | ${Number(p.liq).toFixed(0)} | ${diffPct.toFixed(2)}% |`);
}

const hours = liveSince ? ((Date.now() - liveSince) / 3_600_000).toFixed(1) : "0";
const fmt = (t?: number) => (t ? new Date(t).toISOString().replace("T", " ").slice(0, 16) + " UTC" : "n/a");
const top = Object.entries(reasons).sort((a, b) => b[1] - a[1]);

console.log(`## Results (live on Strike mainnet)

_Generated by \`npm run report\` from the signed ledger at ${fmt(Date.now())}. Ledger integrity: ${valid ? "all hashes, signatures and chain links valid ✓" : "**INVALID ENTRIES FOUND**"}._

- Live since **${fmt(liveSince)}** (${hours} hours), $15 account
- **${decisions.length}** proposals judged: **${v.APPROVE} approved**, **${v.BLOCK} blocked**, **${v.PAUSE} paused**
- **${execs.length}** bracket orders sent to Strike · **${outcomes.length}** closed (${wins} profit, ${losses} loss) · approx. closed P&L **${pnl >= 0 ? "+" : "−"}$${Math.abs(pnl).toFixed(2)}**
- Equity now **$${(hb?.equity ?? 0).toFixed(2)}**

**Why trades were stopped** (a blocked proposal can fail several checks):

| Check | Times it stopped a trade |
|---|---|
${top.map(([n, c]) => `| ${n} | ${c} |`).join("\n") || "| — | 0 |"}
${liqRows.length ? `
**Liquidation estimate vs Strike** (Guardian's isolated-margin formula at Strike's actual entry):

| Position | Guardian estimate | Strike | Difference |
|---|---|---|---|
${liqRows.join("\n")}` : ""}
`);
await store.close();
